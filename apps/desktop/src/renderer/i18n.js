/** 支持的语言 / Supported languages, in the order the segmented control shows them. */
export const LANGS = ['zh', 'en'];

const normalise = (lang) => (lang === 'en' ? 'en' : 'zh');

/**
 * 取一条文案 / One string.
 *
 * 回退顺序：当前语言 → zh → fallback（调用方给的数据字段）→ 键名。
 * 后两层是给 schema 里新增、词典还没跟上的键留的路：宁可显示中文或原始标签，
 * 也不显示一个 dot.path。
 */
export function translate(lang, key, vars, fallback) {
  const table = MESSAGES[normalise(lang)];
  let text = table[key];
  if (text === undefined) text = MESSAGES.zh[key];
  if (text === undefined) text = fallback === undefined ? key : fallback;
  if (!vars) return text;
  /*
   * 单复数 / Singular and plural.
   *
   * 一条英文文案需要两个数时，写成 "one|many"，用 | 分开，由 vars.n 选：
   * '{n} item|{n} items'。中文没有单复数，一个不带 | 的值两边通用，所以这条
   * 规则只影响需要它的英文行。
   */
  if (typeof vars.n === 'number' && String(text).includes('|')) {
    const [one, many] = String(text).split('|');
    text = vars.n === 1 ? one : (many ?? one);
  }
  return String(text).replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match);
}

/** 词典里所有键，排序后便于逐键比对 / Sorted keys of one language table. */
export const keysOf = (lang) => Object.keys(MESSAGES[normalise(lang)]).sort();
